// 2026-10-22: offline exit for the sample exam only. A sample exam has no invigilator, so
// when the server can't be reached the page itself turns the code the locked app shows
// (Mac / PC / iPad code) into the 8-digit exit code, with the attempt's offline key that
// GET /api/student/attempts/{aid}/trial-key handed it earlier (sample exam only; a real
// exam's key never reaches the page). Same rule as the server (app_client.offline_exit_code):
//   code = first 4 bytes of HMAC-SHA256(key, "offline-exit|<CODE>") big-endian, mod 10^8.
// Plain JS on purpose: crypto.subtle only exists on https / localhost pages.

export const APP_CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";

/** "k7qm-3xpa" -> "K7QM3XPA"; null unless it is a code the app can show. */
export function normalizeAppCode(raw: string): string | null {
  const c = (raw || "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  if (c.length !== 8 || [...c].some((ch) => !APP_CODE_ALPHABET.includes(ch))) return null;
  return c;
}

